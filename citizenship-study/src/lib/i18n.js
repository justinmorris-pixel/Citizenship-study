export function makeT(lang) {
  return (key, vars) => {
    let s = (S[lang] && S[lang][key]) || S.en[key] || key
    if (vars) for (const k of Object.keys(vars)) s = s.replaceAll(`{${k}}`, vars[k])
    return s
  }
}
